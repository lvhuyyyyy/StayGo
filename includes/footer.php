<script>
function openFooterSupport() {
    document.getElementById('footerSupportOverlay').classList.add('open');
}
function closeFooterSupport() {
    document.getElementById('footerSupportOverlay').classList.remove('open');
    document.getElementById('footerSpMsg').style.display = 'none';
}
function closeFooterSupportOutside(e) {
    if (e.target === document.getElementById('footerSupportOverlay')) closeFooterSupport();
}
function submitFooterSupport(e) {
    e.preventDefault();
    const form = document.getElementById('footerSupportForm');
    const msg  = document.getElementById('footerSpMsg');
    const btn  = form.querySelector('.sp-submit');
    btn.disabled = true;
    btn.textContent = 'Đang gửi...';
    fetch('/api/contact_support.php', {
        method: 'POST', body: new FormData(form)
    })
    .then(r => r.json())
    .then(res => {
        msg.style.display = 'block';
        msg.className = 'sp-msg ' + (res.success ? 'success' : 'error');
        msg.textContent = res.message;
        if (res.success) { form.reset(); setTimeout(closeFooterSupport, 2500); }
    })
    .catch(() => {
        msg.style.display = 'block';
        msg.className = 'sp-msg error';
        msg.textContent = 'Có lỗi kết nối, vui lòng thử lại!';
    })
    .finally(() => {
        btn.disabled = false;
        btn.textContent = 'Gửi yêu cầu hỗ trợ';
    });
}
</script>
